'use strict';
// Light design: the whole UI is turned with `filter: invert(1) hue-rotate(180deg)` (theme.css). Colours meant for
// the light design are written as they should look (build/light-theme.src.css); this script solves the filter for
// each of them (exact inverse of the CSS hue-rotate(180deg) matrix after invert) and writes the values that end up
// as exactly those colours into app/renderer/theme.css between the GENERATED markers.
const fs = require('node:fs');
const path = require('node:path');

const H = [[-0.574, 1.43, 0.144], [0.426, 0.43, 0.144], [0.426, 1.43, -0.856]];
function inv3(m) {
  const [[a, b, c], [d, e, f], [g, h, i]] = m;
  const det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
  return [[(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
    [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
    [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det]];
}
const Hi = inv3(H);
const rgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
// final colour -> the colour to write before the filter
function pre(hex) {
  const f = rgb(hex);
  return Hi.map((row) => Math.min(255, Math.max(0, Math.round((1 - row.reduce((s, v, k) => s + v * f[k], 0)) * 255))));
}
// what the filter makes of a colour (for the tests)
function filtered(hex) {
  const u = rgb(hex).map((x) => 1 - x);
  return H.map((row) => Math.min(255, Math.max(0, Math.round(row.reduce((s, v, k) => s + v * u[k], 0) * 255))));
}
const toHex = (c) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('');
function convert(css) {
  return css
    .replace(/rgba\(#([0-9a-fA-F]{6}),\s*([0-9.]+)\)/g, (_, h, a) => `rgba(${pre(h).join(', ')}, ${a})`)
    .replace(/(?<![\w-])#([0-9a-fA-F]{6})\b/g, (_, h) => toHex(pre(h)));
}
const START = '/* GENERATED by build/make-light-theme.cjs from build/light-theme.src.css – do not edit by hand */';
const END = '/* END GENERATED */';
function render(root = path.join(__dirname, '..')) {
  const src = fs.readFileSync(path.join(root, 'build', 'light-theme.src.css'), 'utf8').replace(/\r\n/g, '\n').replace(/^\/\*[\s\S]*?\*\/\n/, '');
  const theme = fs.readFileSync(path.join(root, 'app', 'renderer', 'theme.css'), 'utf8').replace(/\r\n/g, '\n');
  const block = `${START}\n${convert(src).trim()}\n${END}`;
  const i = theme.indexOf(START), j = theme.indexOf(END);
  return i >= 0 && j > i ? theme.slice(0, i) + block + theme.slice(j + END.length) : `${theme.trimEnd()}\n\n${block}\n`;
}
if (require.main === module) {
  const file = path.join(__dirname, '..', 'app', 'renderer', 'theme.css');
  fs.writeFileSync(file, render());
  console.log('theme.css updated');
}
module.exports = { pre, filtered, toHex, convert, render };
